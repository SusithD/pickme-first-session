import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
const require = createRequire(path.resolve(fileURLToPath(import.meta.url), '../../prototype/package.json'))
const { chromium } = require('playwright')

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, 'video')
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, recordVideo: { dir: out, size: { width: 1920, height: 1080 } } })
const page = await context.newPage()
await page.goto('file://' + path.join(here, 'stage.html'))
await page.evaluate(() => document.fonts.ready)
const phone = page.frameLocator('#phone')
const pause = (ms) => page.waitForTimeout(ms)
const caption = (n, t, d) => page.evaluate(([n, t, d]) => { document.getElementById('n').textContent = n; document.getElementById('t').textContent = t; document.getElementById('d').textContent = d }, [n, t, d])
const tap = async (loc) => { await loc.waitFor({ state: 'visible' }); await pause(500); await loc.click(); await pause(1400) }

await phone.getByRole('heading', { level: 1 }).waitFor()
await pause(2500)
await tap(phone.getByRole('link', { name: 'Where are you going?' }))
await caption('02', 'Location, asked in context', 'One line on why, and a way to type the pickup instead.')
await pause(1600)
await tap(phone.getByRole('link', { name: 'Type pickup instead' }))
await caption('03', 'Pick a destination', 'Fares are shown before any account exists.')
await pause(1600)
await tap(phone.getByRole('button', { name: 'Fort Railway Station' }))
await caption('04', 'A fixed fare', 'One price per ride type, with what can change it one tap away.')
await pause(2400)
await tap(phone.getByRole('link', { name: 'What can change this?' }))
await caption('05', 'How the fare is made', 'Base, distance and peak add up to the total. Only three things can change it.')
await pause(3200)
await tap(phone.getByRole('button', { name: 'Got it' }))
await tap(phone.getByRole('button', { name: /^Book / }))
await caption('06', 'Sign up at the moment of booking', 'Phone and a 6-digit code, and the fare stays the same.')
const tel = phone.getByRole('textbox', { name: 'Mobile number' })
await tel.waitFor()
await tel.pressSequentially('771234567', { delay: 90 })
await pause(600)
await tel.press('Enter')
const code = phone.getByRole('textbox', { name: '6-digit code' })
await code.waitFor()
await pause(900)
await code.pressSequentially('123456', { delay: 120 })
await code.press('Enter')
await pause(1800)
await tap(phone.getByRole('button', { name: 'Continue' }))
await caption('07', 'A driver who agreed to your payment', 'The driver card shows the method the driver accepted.')
await pause(1500)
const skip = phone.getByRole('button', { name: 'Skip wait' })
if (await skip.isVisible().catch(() => false)) await tap(skip)
await pause(1800)
await tap(phone.getByRole('button', { name: 'Not now' }))
await tap(phone.getByRole('link', { name: 'Continue' }))
await caption('08', 'On the way', 'The fare so far stays visible, and unchanged.')
await pause(2600)
await tap(phone.getByRole('link', { name: 'Arrive at destination' }))
await caption('09', 'The rider can end the trip', 'No waiting for the driver to stop the meter.')
await pause(2000)
await tap(phone.getByRole('button', { name: 'Yes, end my trip' }))
await caption('10', 'A receipt that matches the booking', 'As booked, itemised, and a clear way to get help.')
await pause(4000)
await page.close()
await context.close()
await browser.close()
